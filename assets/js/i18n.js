// Determina il percorso corretto per i file JSON (root vs pages/)
const LOCALES_BASE = (() => {
  const path = window.location.pathname.replace(/\\/g, '/');
  return path.includes('/pages/') ? '../assets/locales/' : 'assets/locales/';
})();

let currentLang = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
let translations = {};

// Carica il file JSON per la lingua richiesta; se fetch fallisce (es. protocollo file://), usa il fallback offline
async function loadLocale(lang) {
  try {
    const res = await fetch(`${LOCALES_BASE}${lang}.json`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    return { ...FALLBACK_TRANSLATIONS[lang], ...data };
  } catch (err) {
    return FALLBACK_TRANSLATIONS[lang] || FALLBACK_TRANSLATIONS[DEFAULT_LANG];
  }
}

// Applica le traduzioni a tutti gli elementi con [data-i18n]
function applyTranslations(t) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && (key in t)) {
      el.innerHTML = t[key];
    }
  });

  // Placeholder form
  const inputs = document.querySelectorAll('.f-input');
  if (inputs.length >= 4) {
    if (t['form_placeholder_name']) inputs[0].placeholder = t['form_placeholder_name'];
    if (t['form_placeholder_email']) inputs[1].placeholder = t['form_placeholder_email'];
    if (t['form_placeholder_phone']) inputs[2].placeholder = t['form_placeholder_phone'];
    if (t['form_placeholder_message']) inputs[3].placeholder = t['form_placeholder_message'];
  }

  // Pulsanti lingua attivi
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });

  document.documentElement.lang = currentLang;

  try {
    window.dispatchEvent(new CustomEvent('dp:lang', { detail: { lang: currentLang, translations: t } }));
  } catch (_) {}
}

// Switcher lingua
async function switchLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  translations = await loadLocale(lang);
  applyTranslations(translations);
}

function bindLangButtons() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => switchLang(btn.dataset.lang));
  });
}

window.DPI18n = {
  getLang: () => currentLang,
  getTranslations: () => translations,
  refresh: () => applyTranslations(translations),
  switchLang
};

// Inizializzazione automatica
(async () => {
  bindLangButtons();
  translations = await loadLocale(currentLang);
  applyTranslations(translations);
})();
